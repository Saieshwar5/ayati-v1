// Copies the web's bundled agent robots (web/public/agent-avatars) into the app
// as SVG strings, so agents show the same faces offline. Run after the robots
// change: node scripts/sync-agent-avatars.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '../../web/public/agent-avatars');
const target = join(here, '../src/faces/robots.ts');
const names = readdirSync(source).filter(name => /^robot-\d\d\.svg$/.test(name)).sort();
if (names.length !== 24) throw new Error(`Expected 24 robots, found ${names.length}`);
const lines = names.map(name => {
  const svg = readFileSync(join(source, name), 'utf8').trim().replace(/\s+/g, ' ');
  return `  '${name.replace('.svg', '')}': ${JSON.stringify(svg)},`;
});
writeFileSync(
  target,
  `// Generated by scripts/sync-agent-avatars.mjs from web/public/agent-avatars. Do not edit.
// Robots: DiceBear 9.4.2 (MIT), style "Bottts Neutral", a remix of "Bottts" by
// Pablo Stanley, free for personal and commercial use (see that folder's LICENSE.md).
export const robots: Record<string, string> = {
${lines.join('\n')}
};
`,
);
console.log(`Wrote ${names.length} robots to src/faces/robots.ts`);
