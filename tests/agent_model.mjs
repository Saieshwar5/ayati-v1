import { test } from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import { setup, until, root } from './fixtures/goose_app.mjs';
const { chromium } = createRequire(join(root, 'web/package.json'))('playwright');

test('model editing and optional candidate test use selected model without replay or automatic retries', { timeout: 60000 }, async t => {
  const app = await setup(t, true, { AYATI_BROWSER: '0', AYATI_MEMORY: '0' });
  const db = new DatabaseSync(join(app.data, 'ayati.sqlite')); t.after(() => db.close());
  const session = () => db.prepare('SELECT session_id FROM runtime_sessions').get()?.session_id;
  await app.done((await app.submit('PREVIOUS_MODEL_CONTEXT')).id);
  const before = session();
  const browser = await chromium.launch(); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  await page.goto(app.base.replace('/api', '/?agent=local-agent'));
  await page.getByRole('button', { name: 'Details', exact: true }).click();
  await page.getByRole('button', { name: 'Edit agent settings' }).click();
  const dialog = page.getByRole('dialog', { name: 'Edit agent', exact: true });
  const model = dialog.getByLabel('Model', { exact: true });
  const testButton = dialog.getByRole('button', { name: 'Test model (optional)' });
  await model.fill('fixture-next');
  assert(await testButton.isDisabled());
  const count = app.provider.requests.length;
  await dialog.locator('#model-test-consent').check(); await testButton.click();
  await dialog.getByText('Settings have not been saved.', { exact: false }).waitFor();
  assert.equal(app.provider.requests.length, count + 1);
  assert.equal(app.provider.requests.at(-1).model, 'fixture-next');
  assert.equal((await app.request('/health')).model, 'fixture');
  assert.equal(session(), before);
  await dialog.getByRole('button', { name: 'Save changes' }).click();
  await dialog.getByText('Saved.', { exact: false }).waitFor();
  assert.equal(app.provider.requests.length, count + 1, 'Saving must not make inference');
  assert.equal(session(), undefined);
  assert.equal((await app.request('/health')).model, 'fixture-next');
  assert.equal((await app.request('/setup')).model, 'fixture-next');
  await app.request('/setup/test', { confirm: true });
  assert.equal(app.provider.requests.at(-1).model, 'fixture-next');
  await app.done((await app.submit('Use the new model')).id);
  assert.equal(app.provider.requests.at(-1).model, 'fixture-next');
  assert(!JSON.stringify(app.provider.requests.at(-1).messages).includes('PREVIOUS_MODEL_CONTEXT'));
  assert.notEqual(session(), before);
  assert((await app.state()).messages.some(m => m.content.includes('PREVIOUS_MODEL_CONTEXT')));
  await mkdir(join(root, '.test-runs/model'), { recursive: true });
  await page.screenshot({ path: join(root, '.test-runs/model/desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: join(root, '.test-runs/model/mobile.png') });
  app.provider.setUnavailable(true);
  await model.fill('unavailable-model');
  await dialog.locator('#model-test-consent').check(); await testButton.click();
  await dialog.getByText('HTTP 403', { exact: false }).waitFor();
  assert.equal((await app.request('/health')).model, 'fixture-next', 'Failed candidate test cannot change saved model');
  app.provider.setUnavailable(false);
  await app.stop(); await app.start();
  assert.equal((await app.request('/health')).model, 'fixture-next');
  await app.done((await app.submit('After restart')).id);
  assert.equal(app.provider.requests.at(-1).model, 'fixture-next');
  const pending = await app.submit('tool stock');
  await until(async () => (await app.state()).permissions.length, 'Missing approval');
  const denied = await fetch(app.base + '/agents/local-agent/profile', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name: 'Ayati', role: '', model: 'fixture', expected_revision: 1 }) });
  assert.equal(denied.status, 400);
  await app.request(`/tasks/${pending.id}/stop`, {}); await app.done(pending.id);
  await app.stop(); await app.start();
  await app.request('/agents/local-agent/profile', { name: 'Ayati', role: '', model: 'fixture', expected_revision: 1 });
  assert.equal(session(), undefined);
  await app.done((await app.submit('Explicitly restored model')).id);
  assert.equal(app.provider.requests.at(-1).model, 'fixture');
});
