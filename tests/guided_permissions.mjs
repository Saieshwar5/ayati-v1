import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';
import { workerFixture } from './fixtures/independent_worker.mjs';
import { fixtureProvider } from './fixtures/goose_provider.mjs';
import { remoteControlMcp } from './fixtures/remote_control_mcp.mjs';
import { until } from './fixtures/goose_app.mjs';
const root = resolve(import.meta.dirname, '..');
const { chromium } = createRequire(join(root, 'web/package.json'))('playwright');

test('guided AI review covers every tool, previews without effects and activates rules that real Goose obeys', { skip: !process.env.RELAY_TEST_DATABASE_URL, timeout: 180000 }, async t => {
  const remote = await remoteControlMcp(); t.after(() => remote.close()); remote.addTool('export_everything');
  const provider = await fixtureProvider();
  const directory = await mkdtemp(join(root, '.tmp/guided-profile-'));
  const profiles = join(directory, 'servers.json'); const bearer = join(directory, 'bearer');
  await writeFile(profiles, '[]', { mode: 0o600 }); await writeFile(bearer, remote.token, { mode: 0o600 });
  const app = await workerFixture(t, { provider, mode: 'pooled', control: true, runSeconds: 90, leaseSeconds: 15, apiEnv: { AYATI_MCP_SERVERS_FILE: profiles, OPENAI_API_KEY: 'fixture-not-a-secret', OPENAI_HOST: provider.url } });
  const w = app.path.split('/').at(-1);
  await writeFile(profiles, JSON.stringify([{ id: 'orders', workspace: w, name: 'Company orders', account: 'Northstar test store', url: remote.url, bearer_file: bearer, operations: remote.operations }]));
  const connection = randomUUID();
  await app.request(`${app.path}/control/systems`, app.cookie, { server: 'orders', approved: true, revision: 0 });
  await app.request(`${app.path}/control/connections`, app.cookie, { id: connection, server: 'orders', enabled: true, revision: 0 });
  const control = `${app.path}/agent-profiles/${app.profile.id}/control`;
  const setup = `${app.path}/agent-profiles/${app.profile.id}/setup`;
  const snapshot = async () => (await app.request(control, app.cookie)).value;
  const member = await app.login(1);
  await app.request(setup, member, undefined, 400);
  const browser = await chromium.launch({ headless: true });
  let page;
  t.after(async () => {
    if (!t.passed && page) {
      await page.screenshot({ path: join(app.data, 'failure.png') }).catch(() => {});
      await writeFile(join(app.data, 'failure.html'), await page.content()).catch(() => {});
    }
    await writeFile(join(app.data, 'setup-model-requests.json'), JSON.stringify(provider.requests, null, 2), { mode: 0o600 });
    await browser.close();
  });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const [name, value] = app.cookie.split('='); await context.addCookies([{ name, value, url: app.base, httpOnly: true, sameSite: 'Lax' }]);
  page = await context.newPage(); const errors = []; page.on('pageerror', error => errors.push(error.message));
  const open = async () => {
    await page.goto(`${app.base}/w/${w}/?view=agents`);
    await page.getByRole('button', { name: 'Set up permissions for Nova', exact: true }).click();
    return page.getByRole('dialog', { name: 'Nova · Set up permissions' });
  };
  let wizard = await open();
  assert.equal(provider.requests.length, 0);
  await wizard.getByLabel('What should this agent do?').fill('Look up orders, ask before address changes and never delete orders.');
  await wizard.getByLabel('Use Company orders', { exact: true }).check();
  await wizard.getByLabel('Work conversation', { exact: true }).selectOption(app.conversation);
  await wizard.getByLabel('Use AI suggestions for this review', { exact: true }).check();
  await wizard.getByRole('button', { name: 'Create review draft', exact: true }).click();
  await wizard.getByLabel('Company orders: Read order permission', { exact: true }).waitFor();
  assert.equal(await wizard.getByLabel('Company orders: Read order permission', { exact: true }).inputValue(), 'allow');
  assert.equal(await wizard.getByLabel('Company orders: Update order permission', { exact: true }).inputValue(), 'ask');
  assert.equal(await wizard.getByLabel('Company orders: Delete order permission', { exact: true }).inputValue(), 'block');
  assert.match(await wizard.innerText(), /3 reviewed actions · 1 unsupported tool · 4 discovered tools/);
  assert.equal(remote.calls.length, 0);
  assert.equal((await snapshot()).rules.length, 0);
  assert.ok(provider.requests.length > 0);
  assert.ok(provider.requests.every(request => (request.tools ?? []).length === 0), 'Suggestion model must have no tools');
  await wizard.getByRole('button', { name: 'Save draft', exact: true }).click();
  await wizard.getByRole('status').filter({ hasText: 'Draft saved' }).waitFor();
  await wizard.getByRole('button', { name: 'Close', exact: true }).click();
  wizard = await open();
  assert.equal(await wizard.getByLabel('Company orders: Update order permission', { exact: true }).inputValue(), 'ask');
  await page.screenshot({ path: join(app.data, 'guided-review-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(app.data, 'guided-review-mobile.png') });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 1280, height: 900 });
  await wizard.getByRole('button', { name: 'Preview permissions', exact: true }).click();
  assert.equal(await wizard.getByRole('button', { name: 'Activate reviewed permissions', exact: true }).isDisabled(), true);
  await wizard.getByLabel('Example order', { exact: true }).fill('one');
  await wizard.getByRole('button', { name: 'Preview example', exact: true }).click();
  await wizard.getByRole('status').filter({ hasText: 'Example: Allow automatically' }).waitFor();
  assert.equal(remote.calls.length, 0); assert.equal((await snapshot()).actions.length, 0);
  await page.screenshot({ path: join(app.data, 'guided-preview-desktop.png') });
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; });
  await page.screenshot({ path: join(app.data, 'guided-preview-dark.png') });
  app.pass('Real tool-free Goose creates a reviewable draft; omissions and unsupported tools stay blocked; saved review survives reload and preview performs zero business actions');

  await wizard.getByLabel('I reviewed these actions, their limits and designated approvers.', { exact: true }).check();
  await wizard.getByRole('button', { name: 'Activate reviewed permissions', exact: true }).click();
  await wizard.getByRole('heading', { name: 'Reviewed permissions activated', exact: true }).waitFor();
  assert.equal((await snapshot()).rules.length, 3);
  const saved = (await app.request(setup, app.cookie)).value.draft;
  const receipt = await app.request(`${setup}/drafts/${saved.id}/activate`, app.cookie, { revision: saved.revision, reviewed: true });
  assert.equal(receipt.value.draft, saved.id);
  assert.ok((await snapshot()).rules.every(rule => rule.revision === 1));
  const worker = await app.startExecutor({ AYATI_EXECUTOR_SLOTS: '1' });
  async function send(operation, args) {
    const job = await app.send(`control ${JSON.stringify({ tool: 'request_action', arguments: { connection, operation, arguments: args } })}`);
    await until(async () => (await app.history()).find(m => m.id === job.reply && (m.state === 'complete' || m.progress?.state === 'approval')), 'Guided agent did not finish', 35000);
    return (await snapshot()).actions.find(action => action.job === job.reply);
  }
  assert.equal((await send('order.read', { order: 'one' })).state, 'completed');
  const pending = await send('order.update', { order: 'one', address: 'Approved after guided setup' });
  assert.equal(pending.state, 'pending');
  await app.request(`${control}/actions/${pending.id}/decision`, app.cookie, { id: randomUUID(), decision: 'approve' });
  assert.equal(remote.records.get('one').address, 'Approved after guided setup');
  assert.equal((await send('order.delete', { order: 'one' })).state, 'denied');
  assert.equal(remote.calls.some(call => call.name === 'delete_order'), false);
  app.pass('Atomic guided activation creates Allow/Ask/Block rules that real Goose obeys; exact activation retry changes no revisions');

  const next = (await app.request(`${setup}/drafts`, app.cookie, { id: randomUUID(), purpose: 'Review after inventory changes', chat: app.conversation, connections: [connection], assistant: false })).value;
  await app.request(`${setup}/drafts/${next.id}/preview`, app.cookie, { revision: next.revision });
  remote.addTool('new_unreviewed_export');
  await app.request(`${setup}/drafts/${next.id}/activate`, app.cookie, { revision: next.revision, reviewed: true }, 400);
  assert.ok((await snapshot()).rules.every(rule => rule.revision === 1));
  await app.stopApi(); await app.startApi();
  assert.equal((await app.request(setup, app.cookie)).value.draft.id, next.id);
  assert.deepEqual(errors, []);
  assert.equal(JSON.stringify(provider.requests).includes(remote.token), false);
  assert.equal(app.processes().some(p => p.logs.includes(remote.token)), false);
  await app.stop(worker);
  app.pass('Changed inventory blocks stale activation, draft survives controller restart, and credentials never reach the model or logs');
});
