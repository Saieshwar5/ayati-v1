import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { mkdir } from 'node:fs/promises';
import { setup, until, root } from './fixtures/goose_app.mjs';
const { chromium } = createRequire(join(root, 'web/package.json'))('playwright');

test('personal Home routes creation through conversations, preserves drafts and publishes only after approval', { timeout: 90000 }, async t => {
  const app = await setup(t, false, { AYATI_BROWSER: '0' });
  const browser = await chromium.launch(); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1024, height: 850 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const base = app.base.replace('/api', '');
  const profile = (await app.request('/agents')).agents[0].profile;
  assert.equal(profile.is_default, true); assert.equal(profile.can_delete, false);
  const normal = await fetch(base); assert.match(normal.headers.get('content-security-policy'), /frame-ancestors 'none'/);
  const guide = await fetch(base + '/?agent=local-agent&guide=1'); assert.match(guide.headers.get('content-security-policy'), /frame-ancestors 'self'/);
  await page.goto(base);
  await page.getByRole('heading', { name: 'What would you like help keeping track of?' }).waitFor();
  await page.getByRole('button', { name: 'Add panel', exact: false }).click();
  await page.getByRole('dialog').getByRole('link', { name: /Ayati/ }).click();
  await page.locator('#input').waitFor();
  assert.equal(await page.locator('#input').inputValue(), '');
  assert.equal(await page.locator('.creation-mode strong').textContent(), 'Creating a panel');
  assert.equal(app.provider.requests.length, 0, 'Choosing an agent must not submit work');
  await page.locator('#input').fill('My previous unsent draft');
  await page.goto(base + '/?view=apps');
  await page.getByRole('button', { name: 'Create app', exact: false }).click();
  await page.getByRole('dialog').getByRole('link', { name: /Ayati/ }).click();
  assert.equal(await page.locator('#input').inputValue(), 'My previous unsent draft');
  assert.equal(await page.locator('.creation-mode strong').textContent(), 'Creating an app');
  await page.getByRole('button', { name: 'Exit creation mode' }).click();
  assert.equal(await page.locator('#input').inputValue(), 'My previous unsent draft');
  await page.goto(base);
  await page.locator('#home-guide').click();
  const frame = page.frameLocator('.guide-drawer iframe');
  await frame.locator('#input').waitFor();
  await frame.locator('#input').fill('Guide drawer draft');
  await page.getByRole('button', { name: 'Close Ayati' }).click();
  await page.locator('#home-guide').click();
  assert.equal(await frame.locator('#input').inputValue(), 'Guide drawer draft');
  assert.equal(await frame.locator('.workspace-rail').isVisible(), false);
  await frame.locator('#input').fill('Help me use Ayati');
  await frame.getByRole('button', { name: 'Send message' }).click();
  await until(async () => (await app.state()).tasks.some(t => t.status === 'completed'), 'Guide did not reply');
  assert(JSON.stringify(app.provider.requests.at(-1)).includes('permanent guide'));
  await page.getByRole('button', { name: 'Close Ayati' }).click();
  const definition = { id: randomUUID(), expected_revision: 0, publish: true, title: 'Weekly sales', purpose: 'Sample figures for interface verification', sources: [], sections: [{kind:'chart',title:'Daily sales',points:[{label:'Mon',value:5000},{label:'Tue',value:6250},{label:'Wed',value:4500},{label:'Thu',value:7000},{label:'Fri',value:9000},{label:'Sat',value:16500}]}] };
  const task = await app.submit('workspace ' + JSON.stringify({ tool: 'panel_write', arguments: definition }));
  const permission = await until(async () => (await app.state()).permissions[0], 'Publication approval missing');
  assert.equal(permission.title, 'Add this panel to Home');
  assert.equal((await app.request('/panels')).panels.length, 0);
  await app.request(`/permissions/${permission.id}`, {allow:true});
  assert.equal((await app.done(task.id)).task.status, 'completed');
  assert.equal((await app.request('/panels')).panels[0].state, 'active');
  await page.getByRole('heading', {name:'Weekly sales',exact:true}).waitFor();
  assert.equal(await page.getByRole('button', {name:'Keep on Home',exact:true}).count(), 0);
  await page.getByRole('button',{name:'Arrange',exact:true}).click();
  await page.getByRole('button',{name:'Make wider',exact:true}).click();
  await page.getByRole('button',{name:'Done arranging',exact:true}).click();
  await page.reload(); await page.locator('.home-panel-card.panel-wide').waitFor();
  await page.locator('.home-panel-card').getByRole('link', { name: 'Ask its agent ↗' }).click();
  assert.equal(await page.locator('.creation-mode strong').textContent(), 'Updating a panel');
  assert.equal(new URL(page.url()).searchParams.get('item'), definition.id);
  await page.locator('.agent-creations > summary').click();
  await page.locator('.agent-creations').getByRole('link', { name: /Weekly sales · On Home/ }).click();
  await page.locator('.home-panel-card').waitFor();
  for (const width of [1024,736,390,320]) {
    await page.setViewportSize({width,height:850});
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Home fits ${width}`);
    await page.locator('#home-guide').click();
    await frame.locator('#composer').waitFor();
    assert(await frame.locator('#composer').evaluate(el => el.getBoundingClientRect().bottom <= innerHeight), `Guide composer fits ${width}`);
    await page.getByRole('button', { name: 'Close Ayati' }).click();
  }
  await page.setViewportSize({width:1024,height:850});
  await mkdir(join(root,'.test-runs/personal-home'),{recursive:true});
  await page.screenshot({path:join(root,'.test-runs/personal-home/desktop.png')});
  await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'}); await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:join(root,'.test-runs/personal-home/mobile-dark.png')});
  const denied = await app.submit('workspace ' + JSON.stringify({tool:'panel_write',arguments:{...definition,id:randomUUID()}}));
  const denial = await until(async () => (await app.state()).permissions[0], 'Denial missing');
  await app.request(`/permissions/${denial.id}`,{allow:false}); await app.done(denied.id);
  assert.equal((await app.request('/panels')).panels.length,1);
  await app.stop();await app.start();assert.equal((await app.request('/panels')).panels[0].state,'active');
  assert.equal((await app.request('/agents')).agents[0].profile.is_default,true);
  assert.deepEqual(errors, []);
});
