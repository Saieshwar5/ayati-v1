import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { setup, root, until } from './fixtures/goose_app.mjs';
const { chromium } = createRequire(join(root, 'web/package.json'))('playwright');

test('Agent Studio tools, attachments, previews, retries and mobile layout', { timeout: 90000 }, async t => {
  const app = await setup(t, false, { AYATI_BROWSER: '0' });
  const browser = await chromium.launch(); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1360, height: 860 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(app.base.replace('/api', '') + '/?agent=local-agent');
  await page.locator('.agent-card .agent-link').waitFor();
  assert.equal(await page.locator('.agent-card .agent-detail, .agent-card .agent-preview, .agent-card .agent-role').count(), 0);
  assert.ok((await page.locator('.agent-card').first().boundingBox()).height <= 48);
  await page.locator('#input').fill('Review the attached inventory');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('heading', { name: 'Agent settings' }).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Automation', exact: true }).click();
  assert.equal(await page.locator('#agent-details').isVisible(), false);
  await page.keyboard.press('Escape');
  await page.locator('#file-input').setInputFiles({ name: 'inventory.txt', mimeType: 'text/plain', buffer: Buffer.from('stock=42\n<script>window.pwned=true</script>') });
  await page.locator('#attachments button').waitFor();
  await page.reload();
  await page.locator('#attachments button').waitFor();
  assert.equal(await page.locator('#input').inputValue(), 'Review the attached inventory');
  await page.getByRole('button', { name: 'Artifacts', exact: true }).click();
  await page.locator('.artifact-open').click();
  await until(async () => (await page.locator('#artifact-preview').textContent()).includes('stock=42'), 'No preview');
  assert.equal(await page.evaluate(() => window.pwned), undefined);
  await page.screenshot({ path: '/tmp/ayati-studio-artifacts.png' });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await until(async () => (await app.state()).messages.some(m => m.role === 'user' && m.content.includes('stock=42')), 'File was not supplied');
  await until(async () => await page.locator('.message.user .sent-attachment').count() === 1, 'Attachment label missing');
  assert.equal((await page.locator('.message.user').textContent()).includes('stock=42'), false);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Artifacts', exact: true }).click();
  assert.equal(await page.locator('#files-panel').evaluate(el => el.matches(':modal')), true);
  await page.keyboard.press('Escape');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: '/tmp/ayati-studio-mobile.png' });
  assert.deepEqual(errors, []);
});
