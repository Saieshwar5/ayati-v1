import { test } from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import { setup, until, root } from './fixtures/goose_app.mjs';
const { chromium } = createRequire(join(root, 'web/package.json'))('playwright');

test('graphite Agents workspace preserves draft and reading position across exclusive responsive work panels', { timeout: 60000 }, async t => {
  const app = await setup(t, true, { AYATI_BROWSER: '0', AYATI_MEMORY: '1' });
  const db = new DatabaseSync(join(app.data, 'ayati.sqlite'));
  for (let i = 0; i < 24; i++) {
    db.prepare("INSERT INTO tasks(id,status,context) VALUES(?,'completed','[]')").run(`layout-${i}`);
    db.prepare("INSERT INTO messages(id,task_id,role,content,state) VALUES(?,?,'assistant',?,'complete')").run(`message-${i}`, `layout-${i}`, i === 23 ? '<img src=x onerror=alert(1)> stays plain text' : `Report ${i}: ${'A useful business update. '.repeat(25)}`);
  }
  db.close();
  const browser = await chromium.launch(); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, colorScheme: 'light' });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const dir = join(root, '.test-runs/agents-workspace'); await mkdir(dir, { recursive: true });
  const base = app.base.replace('/api', '');
  await page.goto(base + '/?agent=local-agent');
  await page.locator('.message').last().waitFor();
  assert.match(await page.locator('.message').last().textContent(), /<img src=x/);
  assert.equal(await page.locator('.message img').count(), 0);
  assert.equal(await page.locator('.agent-preview').count(), 0);
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()), '#242630');
  await page.locator('#input').fill('Preserve my draft across tools');
  await page.locator('#agent-sidebar-toggle').click();
  assert.equal(await page.locator('.agents-list').isVisible(), false);
  await page.locator('#agent-sidebar-toggle').click();
  await page.locator('#conversation').evaluate(el => { el.scrollTop = 150; });
  const reading = await page.locator('#conversation').evaluate(el => el.scrollTop);
  await page.screenshot({ path: join(dir, 'conversation-light.png') });
  await page.locator('#automation-button').click();
  await page.getByText('Schedules are up to date.', { exact: true }).waitFor();
  assert.equal(await page.locator('.work-panel[open]').count(), 1);
  assert.equal(await page.locator('#agent-schedules').evaluate(el => el.matches(':modal')), false);
  assert.equal(await page.locator('#input').inputValue(), 'Preserve my draft across tools');
  const chat = await page.locator('.chat').boundingBox(), panel = await page.locator('#agent-schedules').boundingBox();
  assert.ok(chat.x + chat.width <= panel.x + 1);
  await page.locator('#triggers-tab').click();
  await page.getByText('No event triggers for this agent.', { exact: true }).waitFor();
  assert.equal(await page.locator('#schedule-form').isVisible(), false);
  await page.keyboard.press('ArrowLeft');
  assert.equal(await page.locator('#schedules-tab').getAttribute('aria-selected'), 'true');
  await page.screenshot({ path: join(dir, 'automation-light.png') });
  // Closing returns the original transcript width and reading position.
  await page.getByRole('button', { name: 'Close automation' }).click();
  assert.ok(Math.abs(await page.locator('#conversation').evaluate(el => el.scrollTop) - reading) < 4);
  await page.locator('#details-button').click();
  await page.locator('#agent-details').getByRole('button', { name: 'Memory', exact: true }).click();
  assert.equal(await page.locator('#agent-details').isHidden(), true);
  assert.equal(await page.locator('.work-panel[open]').count(), 1);
  await page.getByRole('button', { name: 'Close memory', exact: true }).click();
  await page.locator('#details-button').click();
  await page.locator('#agent-details').getByRole('button', { name: 'Files', exact: true }).click();
  assert.equal(await page.locator('#agent-details').isHidden(), true);
  assert.equal(await page.locator('.work-panel[open]').count(), 1);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.work-panel[open]').count(), 0);
  await page.locator('#automation-button').click();
  await page.setViewportSize({ width: 390, height: 844 });
  await until(() => page.locator('#agent-schedules').evaluate(el => el.matches(':modal')), 'Automation did not become modal');
  await page.keyboard.press('Tab');
  assert.equal(await page.locator('#agent-schedules').evaluate(el => el.contains(document.activeElement)), true);
  await page.screenshot({ path: join(dir, 'automation-mobile.png') });
  await page.setViewportSize({ width: 1440, height: 960 });
  await until(() => page.locator('#agent-schedules').evaluate(el => !el.matches(':modal') && el.open), 'Automation did not return beside chat');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#input').inputValue(), 'Preserve my draft across tools');
  const approvalRun = await app.submit('tool Inspect the synthetic stock');
  await until(async () => (await page.locator('#connection').textContent()) === 'Waiting for your approval', 'Header did not show pending approval');
  await page.locator('#stop').click();
  assert.equal((await app.done(approvalRun.id)).task.status, 'stopped');
  await until(async () => (await page.locator('#connection').textContent()) === 'Ready', 'Header did not return to Ready');
  assert.equal(await page.locator('#input').inputValue(), 'Preserve my draft across tools');
  await page.getByRole('navigation', { name: 'Workspace' }).getByRole('link', { name: 'Settings', exact: true }).click();
  await page.locator('#theme').selectOption('dark');
  await page.getByRole('navigation', { name: 'Workspace' }).getByRole('link', { name: 'Agents', exact: true }).click();
  assert.equal(await page.locator('#input').inputValue(), 'Preserve my draft across tools');
  await page.screenshot({ path: join(dir, 'conversation-dark.png') });
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    await page.locator('#agent-list-toggle').click();
    await page.getByRole('button', { name: 'Back to conversation' }).click();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.ok(await page.locator('#composer').evaluate(el => el.getBoundingClientRect().bottom <= innerHeight));
  }
  await page.screenshot({ path: join(dir, 'conversation-mobile-dark.png') });
  assert.deepEqual(errors, []);
});
