import { test } from 'node:test';
import assert from 'node:assert/strict';
import { setup, until } from './fixtures/goose_app.mjs';
import { composioFixture } from './fixtures/composio.mjs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { mkdir } from 'node:fs/promises';
import { root } from './fixtures/goose_app.mjs';
const { chromium } = createRequire(join(root, 'web/package.json'))('playwright');

test('Composio grants fence actual Goose/MCP execution, lost replies and restart', { timeout: 90000 }, async t => {
  const provider = await composioFixture(); t.after(provider.close);
  const app = await setup(t, false, { COMPOSIO_API_KEY: 'fixture-composio-key', AYATI_COMPOSIO_BASE_URL: provider.url, AYATI_MEMORY: '0', AYATI_BROWSER: '0' });
  const configs = await app.request('/connections/configs');
  assert(!JSON.stringify(configs).includes('DO_NOT_EXPOSE'));
  const linked = await app.request('/connections', { toolkit: 'gmail', auth_config_id: 'ac_fixture', label: 'Synthetic Gmail' });
  assert(!JSON.stringify(linked).includes('DO_NOT_EXPOSE'));
  await app.request(`/connections/${linked.id}/refresh`, {});
  const grant = { tool: 'GMAIL_FETCH_EMAILS', version: '20261001_00', enabled: true };
  await app.request(`/connections/${linked.id}/grants`, grant);
  const args = { connection_id: linked.id, tool: grant.tool, arguments: { max_results: 1 } };
  const count = () => provider.calls.filter(c => c.path.includes('/tools/execute/')).length;
  async function run(arguments_, beforeApprove = async () => {}) {
    const task = await app.submit('workspace ' + JSON.stringify({ tool: 'connector_execute', arguments: arguments_ }));
    const pending = await until(async () => (await app.state()).permissions?.[0], 'Business approval missing');
    await beforeApprove();
    await app.request(`/permissions/${pending.id}`, { allow: true });
    return app.done(task.id);
  }
  let outcome = await run(args);
  assert.equal(outcome.task.status, 'completed'); assert.equal(count(), 1);
  assert(outcome.state.messages.some(m => m.content.includes('Synthetic stock update')));
  const executed = provider.calls.find(c => c.path.includes('/tools/execute/')).body;
  assert.equal(executed.connected_account_id, 'ca_fixture'); assert.equal(executed.version, grant.version);
  assert.equal(executed.user_id, provider.calls.find(c => c.path.endsWith('/link')).body.user_id);
  const listed = await app.request('/connections'); assert(!JSON.stringify(listed).includes('DO_NOT_EXPOSE'));
  await run(args, async () => { await app.request(`/connections/${linked.id}/grants`, { ...grant, enabled: false }); });
  assert.equal(count(), 1, 'Revocation while waiting approval must block execution');
  await app.request(`/connections/${linked.id}/grants`, grant);
  provider.foreign(true); await run(args); provider.foreign(false);
  assert.equal(count(), 1, 'Foreign account must be rejected before dispatch');
  provider.active(false); await run(args); provider.active(true);
  assert.equal(count(), 1, 'Expired account must be rejected before dispatch');
  provider.loseReply(true); outcome = await run(args); provider.loseReply(false);
  assert.equal(count(), 2, 'Lost replies must not automatically retry the operation');
  assert.notEqual(outcome.task.status, 'completed');
  assert.equal((await app.request('/connector-executions')).executions[0].status, 'uncertain');
  await app.stop(); await app.start();
  assert.equal(count(), 2); assert.equal((await app.request('/connections')).grants.length, 1);
  await app.request(`/connections/${linked.id}/revoke`, {});
  await run(args); assert.equal(count(), 2);
  assert.equal((await app.request('/connections')).grants.length, 0);
  await app.stop(); await app.start();
  assert.equal((await app.request('/connections')).connections[0].status, 'REVOKED');
});

test('owner can link an account and grant an operation through the responsive UI', { timeout: 60000 }, async t => {
  const provider = await composioFixture(); t.after(provider.close);
  const app = await setup(t, false, { COMPOSIO_API_KEY: 'fixture-composio-key', AYATI_COMPOSIO_BASE_URL: provider.url });
  const browser = await chromium.launch(); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await page.goto(app.base.replace('/api', '/?view=settings'));
  await page.getByRole('button', { name: 'Connect Google account', exact: true }).click();
  await page.getByRole('textbox', { name: 'Account label', exact: true }).fill('Owner Gmail fixture');
  await page.getByRole('button', { name: 'Create sign-in link', exact: true }).click();
  await page.getByRole('link', { name: 'Continue to Google sign-in', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Refresh account', exact: true }).click();
  await page.getByText('gmail · ACTIVE', { exact: true }).waitFor();
  assert(!(await page.content()).includes('DO_NOT_EXPOSE'));
  await page.goto(app.base.replace('/api', '/?agent=local-agent'));
  await page.getByRole('button', { name: 'Details', exact: true }).click();
  await page.getByRole('button', { name: 'Choose operations', exact: true }).click();
  await page.getByRole('button', { name: 'Grant to this agent', exact: true }).click();
  await page.getByRole('button', { name: 'Remove grant', exact: true }).waitFor();
  assert.equal((await app.request('/connections')).grants.length, 1);
  await mkdir(join(root, '.test-runs/connections'), { recursive: true });
  await page.screenshot({ path: join(root, '.test-runs/connections/mobile.png'), fullPage: true });
  await page.getByRole('button', { name: 'Remove grant', exact: true }).click();
  await page.getByRole('button', { name: 'Grant to this agent', exact: true }).waitFor();
  assert.equal((await app.request('/connections')).grants.length, 0);
});
