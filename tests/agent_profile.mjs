import { test } from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import { setup, until, root } from './fixtures/goose_app.mjs';
const { chromium } = createRequire(join(root, 'web/package.json'))('playwright');

test('profile editing preserves history, resets role context, rejects busy/stale edits and survives restart', { timeout: 60000 }, async t => {
  const app = await setup(t, true, { AYATI_BROWSER: '0', AYATI_MEMORY: '0' });
  const db = new DatabaseSync(join(app.data, 'ayati.sqlite')); t.after(() => db.close());
  const session = () => db.prepare('SELECT session_id FROM runtime_sessions').get()?.session_id;
  const profile = async () => (await app.request('/agents')).agents[0].profile;
  const edit = (name, role, revision) => app.request('/agents/local-agent/profile', { name, role, expected_revision: revision });
  const originalTask = await app.submit('OLD_CONTEXT_MARKER'); assert.equal((await app.done(originalTask.id)).task.status, 'completed');
  const originalSession = session();
  await edit('Renamed agent', '', 0);
  assert.equal(session(), originalSession);
  await app.done((await app.submit('Name-only check')).id);
  assert.equal(session(), originalSession);
  const browser = await chromium.launch(); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(app.base.replace('/api', '/?agent=local-agent'));
  await page.getByRole('button', { name: 'Details', exact: true }).click();
  await page.getByRole('button', { name: 'Edit agent settings' }).click();
  const dialog = page.getByRole('dialog', { name: 'Edit agent', exact: true });
  await dialog.getByLabel('Name', { exact: true }).fill('Inventory helper');
  await dialog.getByLabel('Responsibilities').fill('NEW_ROLE_MARKER: help with inventory.');
  await dialog.getByRole('button', { name: 'Save changes' }).click();
  await dialog.getByText('Saved.', { exact: false }).waitFor();
  assert.equal(session(), undefined);
  assert.equal((await profile()).revision, 2);
  await mkdir(join(root, '.test-runs/profile'), { recursive: true });
  await page.screenshot({ path: join(root, '.test-runs/profile/mobile.png') });
  await dialog.getByRole('button', { name: 'Close profile editor' }).click();
  await until(async () => (await page.locator('#details-role').innerText()).includes('NEW_ROLE_MARKER'), 'Details did not refresh');
  await app.done((await app.submit('New role check')).id);
  assert.notEqual(session(), originalSession);
  const sent = JSON.stringify(app.provider.requests.at(-1).messages);
  assert(sent.includes('NEW_ROLE_MARKER'));
  assert(!sent.includes('OLD_CONTEXT_MARKER'));
  assert((await app.state()).messages.some(m => m.content.includes('OLD_CONTEXT_MARKER')));
  const badPost = async body => fetch(app.base + '/agents/local-agent/profile', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  assert.equal((await badPost({ name: 'stale', role: 'old', expected_revision: 1 })).status, 400);
  assert.equal((await badPost({ name: 'bad', role: 'old', browser: true, expected_revision: 2 })).ok, false);
  const task = await app.submit('tool Check stock');
  await until(async () => (await app.state()).permissions.length, 'No pending approval');
  assert.equal((await badPost({ name: 'busy', role: 'old', expected_revision: 2 })).status, 400);
  const queued = await app.submit('queued request');
  await app.request(`/tasks/${queued.id}/stop`, {});
  await app.request(`/tasks/${task.id}/stop`, {}); await app.done(task.id);
  await app.stop(); await app.start();
  assert.equal((await profile()).name, 'Inventory helper');
  assert.equal((await profile()).revision, 2);
  await app.done((await app.submit('After restart')).id);
  assert(JSON.stringify(app.provider.requests.at(-1).messages).includes('NEW_ROLE_MARKER'));
  assert.deepEqual(errors, []);
});
